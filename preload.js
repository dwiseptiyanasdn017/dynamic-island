const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  getConfig: () => ipcRenderer.invoke('cfg:get'),
  getDefault: () => ipcRenderer.invoke('cfg:default'),
  saveConfig: cfg => ipcRenderer.invoke('cfg:save', cfg),
  onConfig: cb => ipcRenderer.on('cfg:updated', (e, c) => cb(c)),
  onMedia: cb => ipcRenderer.on('media:update', (e, m) => cb(m)),
  setIgnore: ignore => ipcRenderer.send('mouse:ignore', ignore),
  media: cmd => ipcRenderer.send('media:cmd', cmd),
  open: target => ipcRenderer.send('open:target', target),
  notify: (title, body) => ipcRenderer.send('notify', { title, body }),
  openSettings: () => ipcRenderer.send('settings:open'),
  openConfigFolder: () => ipcRenderer.send('cfg:folder'),
  openKelas: arg => ipcRenderer.send('kelas:open', arg),
  posisi: () => ipcRenderer.invoke('island:pos'),
  geser: (x, y) => ipcRenderer.send('island:geser', x, y),
  lepas: rect => ipcRenderer.send('island:lepas', rect),
  resetPosisi: () => ipcRenderer.send('island:reset'),
  onAnchor: cb => ipcRenderer.on('island:anchor', (e, a) => cb(a)),
  kontrol: cmd => ipcRenderer.send('kontrol:cmd', cmd),
  onKontrol: cb => ipcRenderer.on('kontrol:status', (e, s) => cb(s)),
  cuaca: () => ipcRenderer.invoke('cuaca'),
  onCuaca: cb => ipcRenderer.on('cuaca', (e, c) => cb(c)),
  segarkanCuaca: () => ipcRenderer.send('cuaca:segarkan'),
  widgetUkuran: (w, h) => ipcRenderer.send('widget:ukuran', w, h),
  widgetSkala: s => ipcRenderer.send('widget:skala', s),
  widgetSkala100: () => ipcRenderer.send('widget:skala100'),
  simpanTugas: list => ipcRenderer.send('tugas:simpan', list),
  simpanCatatan: teks => ipcRenderer.send('catatan:simpan', teks),
  pilihMotivasi: idx => ipcRenderer.send('motivasi:pilih', idx),
  defaultConfig: () => ipcRenderer.invoke('cfg:bawaan'),
  widgetReset: () => ipcRenderer.send('widget:reset'),
  versi: () => ipcRenderer.invoke('update:status'),
  onUpdate: cb => ipcRenderer.on('update:status', (e, s) => cb(s)),
  onUpdateSiap: cb => ipcRenderer.on('update:siap', (e, v) => cb(v)),
  periksaUpdate: () => ipcRenderer.send('update:periksa'),
  pasangUpdate: () => ipcRenderer.send('update:pasang'),
  ikonPintasan: (target, segar) => ipcRenderer.invoke('ikon:pintasan', target, segar),
  karakterSimpan: (dataUrl, nama) => ipcRenderer.invoke('karakter:simpan', dataUrl, nama),
  karakterData: id => ipcRenderer.invoke('karakter:data', id),
  karakterHapus: id => ipcRenderer.invoke('karakter:hapus', id),
  internet: () => ipcRenderer.invoke('sistem:internet'),
  onInternet: cb => ipcRenderer.on('sistem:internet', (e, s) => cb(s)),
  onKelasBuka: cb => ipcRenderer.on('kelas:buka', (e, a) => cb(a)),
  bk: {
    status: () => ipcRenderer.invoke('bk:status'),
    onStatus: cb => ipcRenderer.on('bk:status', (e, s) => cb(s)),
    masuk: (email, pw) => ipcRenderer.invoke('bk:masuk', email, pw),
    keluar: () => ipcRenderer.invoke('bk:keluar'),
    muat: tgl => ipcRenderer.invoke('bk:muat', tgl),
    absen: tgl => ipcRenderer.invoke('bk:absen', tgl),
    setAbsen: (sid, tgl, v) => ipcRenderer.invoke('bk:setAbsen', sid, tgl, v),
    nilai: mapelId => ipcRenderer.invoke('bk:nilai', mapelId),
    setNilai: (sid, mapelId, kunci, v) => ipcRenderer.invoke('bk:setNilai', sid, mapelId, kunci, v),
    jurnal: tgl => ipcRenderer.invoke('bk:jurnal', tgl),
    simpanJurnal: j => ipcRenderer.invoke('bk:simpanJurnal', j),
    hapusJurnal: k => ipcRenderer.invoke('bk:hapusJurnal', k)
  }
});
